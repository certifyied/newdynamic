export const getBrandProductCategory = (product: BrandProduct, brandName: string): string => {
  if (product.category) return product.category;
  const t = product.title.toUpperCase();
  if (t.includes("HMI") || t.includes("PANEL") || t.includes("TOUCH")) return "HMI";
  if (t.includes("PLC") || (t.includes("CONTROLLER") && !t.includes("TEMP"))) return "PLC";
  if (t.includes("DRIVE") || t.includes("VFD") || t.includes("INVERTER") || t.includes("SOFT STARTER")) return "INVERTERS & DRIVES";
  if (t.includes("SERVO") || t.includes("MOTOR") || t.includes("GEARBOX") || t.includes("ACTUATOR")) return "AC SERVO & MOTORS";
  if (t.includes("TEMPERATURE")) return "TEMPERATURE CONTROLLERS";
  if (t.includes("TIMER") || t.includes("COUNTER") || t.includes("TACHOMETER")) return "TIMERS & COUNTERS";
  if (t.includes("RELAY") || t.includes("CONTACTOR") || t.includes("MCB") || t.includes("SWITCHGEAR") || t.includes("BREAKER")) return "LOW VOLTAGE SWITCHGEAR";
  if (t.includes("SENSOR") || t.includes("ENCODER") || t.includes("CAMERA") || t.includes("SWITCH")) return "SENSORS";
  if (t.includes("SCADA") || t.includes("SOFTWARE")) return "SOFTWARE & SCADA";
  if (t.includes("PC") || t.includes("CHASSIS") || t.includes("COMPUTER") || t.includes("GATEWAY") || t.includes("NETWORKING")) return "INDUSTRIAL PC & IOT";
  if (t.includes("BALL SCREW") || t.includes("LINEAR")) return "MOTION & GUIDES";
  if (t.includes("METER") || t.includes("POWER SUPPLY") || t.includes("SMPS")) return "POWER & METERS";
  return brandName.toUpperCase();
};

export const getBrandProductDescription = (product: BrandProduct, brandName: string): string => {
  if (product.description) return product.description;
  const t = product.title.toUpperCase();
  if (t.includes("HMI")) {
    return `The ${brandName} ${product.title} features an advanced touchscreen interface designed for high-resolution visualization, real-time machine monitoring, and intuitive operator workflow.`;
  }
  if (t.includes("PLC")) {
    return `Engineered for high-speed industrial processing, ${brandName} ${product.title} offers scalable I/O expansion, robust communication protocols, and deterministic control reliability.`;
  }
  if (t.includes("DRIVE") || t.includes("VFD") || t.includes("INVERTER") || t.includes("SOFT STARTER")) {
    return `High-efficiency ${brandName} ${product.title} provides precise variable frequency motor speed control, superior torque response, and intelligent energy management for industrial drives.`;
  }
  if (t.includes("SERVO") || t.includes("MOTOR")) {
    return `State-of-the-art ${brandName} ${product.title} delivering rapid dynamic acceleration, sub-micron positioning accuracy, and seamless integration for demanding motion systems.`;
  }
  if (t.includes("GEARBOX")) {
    return `Precision-machined ${brandName} ${product.title} engineered with low backlash, high torsional rigidity, and superior torque transmission for precision automation machinery.`;
  }
  if (t.includes("TEMPERATURE CONTROLLER")) {
    return `Advanced ${brandName} ${product.title} equipped with smart PID tuning algorithms, multi-sensor input support, and high-accuracy thermal regulation across process industries.`;
  }
  if (t.includes("TIMER") || t.includes("COUNTER") || t.includes("TACHOMETER")) {
    return `Reliable ${brandName} ${product.title} offering high-precision interval timing, multi-mode counting operations, and clear digital displays for factory automation lines.`;
  }
  if (t.includes("RELAY") || t.includes("CONTACTOR") || t.includes("MCB") || t.includes("SWITCHGEAR")) {
    return `Heavy-duty ${brandName} ${product.title} providing dependable circuit protection, overload safety, and electrical switching designed for rugged industrial power distribution.`;
  }
  if (t.includes("SENSOR") || t.includes("ENCODER") || t.includes("CAMERA") || t.includes("SWITCH")) {
    return `High-sensitivity ${brandName} ${product.title} ensuring exceptional detection accuracy, rapid switching response, and robust environmental protection in harsh factory conditions.`;
  }
  if (t.includes("SCADA") || t.includes("SOFTWARE")) {
    return `Comprehensive ${brandName} ${product.title} solution offering centralized plant monitoring, real-time data acquisition, alarm logging, and intelligent analytics integration.`;
  }
  if (t.includes("PC") || t.includes("COMPUTER") || t.includes("CHASSIS") || t.includes("GATEWAY") || t.includes("NETWORKING")) {
    return `Ruggedized ${brandName} ${product.title} built for 24/7 mission-critical operations, wide temperature endurance, and high-performance edge computing in automated facilities.`;
  }
  if (t.includes("LINEAR") || t.includes("BALL SCREW")) {
    return `High-precision ${brandName} ${product.title} providing smooth mechanical motion, minimal friction, and exceptional load-bearing durability for automated linear axis systems.`;
  }
  return `Official ${brandName} ${product.title} industrial automation component engineered to global manufacturing standards for superior durability, efficiency, and seamless system integration.`;
};

